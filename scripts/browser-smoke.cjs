const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({...(process.env.BROWSER_CHANNEL ? {channel: process.env.BROWSER_CHANNEL} : {}), headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1100}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = process.env.BASE_URL || 'http://127.0.0.1:8000';
  await page.goto(base);
  await page.locator('input[name="username"]').fill('owner');
  await page.locator('input[name="password"]').fill(process.env.DEMO_PASSWORD || 'AltabDemo!2026');
  await page.getByRole('button', {name: 'Sign in to workspace'}).click();
  await page.getByRole('heading', {name: 'Your store, at a glance.'}).waitFor();
  fs.mkdirSync('test-results', {recursive: true});
  await page.screenshot({path: 'test-results/dashboard-desktop.png', fullPage: true});
  for (const tab of ['orders','products','inventory','purchases','customers','suppliers','accounting','reports','settings','help']) {
    await page.goto(`${base}/#${tab}`);
    await page.locator('main h1').waitFor();
    assert.equal(await page.locator('main h1').count(), 1, `${tab} should render`);
  }
  await page.goto(`${base}/#pos`);
  const product = await page.evaluate(async () => (await (await fetch('/api/state/')).json()).products.find(p => p.available > 3));
  await page.locator('#page-search').fill(product.barcode);
  await page.locator('#page-search').press('Enter');
  await page.locator('.cart-item').waitFor();
  assert.equal(await page.locator('.cart-item').count(), 1);
  await page.getByRole('button', {name: 'Hold sale', exact: true}).click();
  await page.getByRole('button', {name: 'Resume (1)', exact: true}).click();
  await page.locator('#sale-discount').fill('10');
  await page.getByRole('button', {name: 'Complete sale', exact: true}).click();
  await page.getByRole('heading', {name: 'Another happy customer.'}).waitFor();
  const receiptLink = await page.locator('.modal a').getAttribute('href');
  const saleId = Number(receiptLink.split('/')[2]);
  const after = await page.evaluate(async () => (await (await fetch('/api/state/')).json()));
  assert.equal(after.products.find(p => p.id === product.id).available, product.available - 1);
  const receipt = await page.request.get(base + receiptLink);
  assert.equal(receipt.status(), 200);
  await page.getByRole('button', {name: 'Next sale'}).click();
  await page.goto(`${base}/#orders`);
  await page.locator(`[data-action="order:${saleId}"]`).first().click();
  await page.getByRole('button', {name: 'Return items'}).click();
  await page.locator('.sell-form[data-kind=return] [name=reason]').fill('Smoke test return');
  await page.getByRole('button', {name: 'Record return', exact: true}).click();
  await page.getByRole('heading', {name: 'Return recorded'}).waitFor();
  await page.getByRole('button', {name: 'Done'}).click();
  await page.waitForFunction(() => !document.querySelector('.modal'));
  const restored = await page.evaluate(async () => (await (await fetch('/api/state/')).json()));
  assert.equal(restored.products.find(p => p.id === product.id).available, product.available);
  await page.goto(`${base}/shop/`);
  await page.locator(`[data-action="add:${product.id}"]`).click();
  await page.getByRole('button', {name: 'Cart (1)'}).click();
  await page.getByRole('button', {name: 'Continue to checkout'}).click();
  await page.locator('input[name="name"]').fill('Browser smoke test');
  await page.locator('input[name="phone"]').fill('01700000000');
  await page.locator('input[name="address"]').fill('Demo test address, Dhaka');
  await page.getByRole('button', {name: 'Place order'}).click();
  await page.getByRole('heading', {name: 'Your order is in!'}).waitFor();
  const tracking = (await page.locator('.tracking-id').textContent()).trim();
  const tracked = await (await page.request.get(base + '/api/track/?id=' + tracking)).json();
  assert.equal(tracked.status, 'Pending');
  await page.getByRole('button', {name: 'Continue shopping'}).click();
  await page.screenshot({path: 'test-results/storefront-desktop.png', fullPage: true});
  // Cancel the test's online order so the demo stock is restored.
  await page.goto(`${base}/#orders`);
  const pending = await page.evaluate(async tracking => (await (await fetch('/api/state/')).json()).orders.find(o => o.tracking_id === tracking), tracking);
  await page.locator(`[data-action="order:${pending.id}"]`).first().click();
  await page.getByRole('button', {name: 'Cancel order', exact: true}).click();
  await page.waitForFunction(() => !document.querySelector('.modal'));
  await page.setViewportSize({width: 390, height: 844});
  await page.goto(base);
  await page.getByRole('heading', {name: 'Your store, at a glance.'}).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'No mobile horizontal overflow');
  await page.screenshot({path: 'test-results/dashboard-mobile.png', fullPage: true});
  await page.getByRole('button', {name: 'Open menu'}).click();
  await page.locator('.nav-item[href="#pos"]').click();
  await page.getByRole('heading', {name: 'Ready for the next customer.'}).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'POS fits mobile viewport');
  await page.goto(`${base}/shop/`);
  await page.locator('.product-card').first().waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Storefront fits mobile viewport');
  await page.screenshot({path: 'test-results/storefront-mobile.png', fullPage: true});
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: navigation, barcode POS, held sale, receipt, return, online checkout/tracking, mobile layouts, no JS errors.');
})().catch(error => { console.error(error); process.exit(1); });
